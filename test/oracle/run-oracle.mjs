// ---- Seeded PRNG (mulberry32) for reproducible fuzzing ------------------------
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const MEDIA_POOL = [
  ['application', 'json'],
  ['application', 'xml'],
  ['application', 'vnd.shop.v2+json'],
  ['text', 'html'],
  ['text', 'plain'],
];
const LANG_POOL = ['en', 'en-gb', 'fr', 'fr-ca', 'de', 'zh', 'ja'];
const Q_POOL = ['1', '0.9', '0.5', '0.1', '0'];

function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

function randomResource(rng) {
  const count = 1 + Math.floor(rng() * 6);
  const reps = [];
  for (let i = 0; i < count; i += 1) {
    const [type, subtype] = pick(rng, MEDIA_POOL);
    const lang = pick(rng, LANG_POOL);
    const params = rng() < 0.3 ? { version: pick(rng, ['1', '2']) } : {};
    reps.push(rep(`v${i}-${type}-${subtype}-${lang}`.replace(/[^a-z0-9-]/gi, ''), type, subtype, lang, params));
  }
  return resource('fuzz', reps);
}

function randomAccept(rng, res) {
  if (rng() < 0.12) return null; // absent header
  const n = 1 + Math.floor(rng() * 3);
  const ranges = [];
  for (let i = 0; i < n; i += 1) {
    const shape = rng();
    let range;
    if (shape < 0.18) range = '*/*';
    else if (shape < 0.36) range = `${pick(rng, MEDIA_POOL)[0]}/*`;
    else {
      const [type, subtype] = pick(rng, MEDIA_POOL);
      range = `${type}/${subtype}`;
      if (rng() < 0.25) range += `;version=${pick(rng, ['1', '2'])}`;
    }
    const q = pick(rng, Q_POOL);
    if (q !== '1' || rng() < 0.3) range += `;q=${q}`;
    ranges.push(range);
  }
  return ranges.join(', ');
}

function randomLanguages(rng) {
  if (rng() < 0.12) return null;
  const n = 1 + Math.floor(rng() * 3);
  const ranges = [];
  for (let i = 0; i < n; i += 1) {
    let range;
    if (rng() < 0.2) range = '*';
    else {
      const base = pick(rng, LANG_POOL);
      // Sometimes ask for a regional tag that may need truncation fallback.
      range = rng() < 0.3 && !base.includes('-') ? `${base}-us` : base;
    }
    const q = pick(rng, Q_POOL);
    if (q !== '1' || rng() < 0.3) range += `;q=${q}`;
    ranges.push(range);
  }
  return ranges.join(', ');
}

// ---- Run ----------------------------------------------------------------------
let failures = 0;

log('hand-vectors', `validating ${VECTORS.length} hand-computed vectors`);
VECTORS.forEach((v, i) => {
  const coreTrace = negotiate({ resource: v.resource, acceptHeader: v.accept, acceptLanguageHeader: v.lang });
  const coreResult = coreTrace.failure ? { failure: coreTrace.failure.code } : { winner: coreTrace.winner.representationId };
  const oracleResult = oracleDecide(v.resource, v.accept, v.lang);
  const coreOk = JSON.stringify(coreResult) === JSON.stringify(v.expect);
  const oracleOk = JSON.stringify(oracleResult) === JSON.stringify(v.expect);
  const agree = JSON.stringify(coreResult) === JSON.stringify(oracleResult);
  if (!coreOk || !oracleOk || !agree) {
    failures += 1;
    log('hand-vectors', 'MISMATCH', { i, name: v.name, accept: v.accept, lang: v.lang, expect: v.expect, core: coreResult, oracle: oracleResult });
  } else {
    log('hand-vectors', `vector ${i + 1}/${VECTORS.length} ok: ${v.name} -> ${JSON.stringify(coreResult)}`);
  }
});

log('fuzz', `starting differential fuzz`, { iterations: ITERATIONS, seed: SEED });
const rng = mulberry32(SEED);
let agreements = 0;
for (let i = 0; i < ITERATIONS; i += 1) {
  const res = randomResource(rng);
  const accept = randomAccept(rng, res);
  const lang = randomLanguages(rng);

  let coreResult;
  let coreThrew = null;
  try {
    const trace = negotiate({ resource: res, acceptHeader: accept, acceptLanguageHeader: lang });
    coreResult = trace.failure ? { failure: trace.failure.code } : { winner: trace.winner.representationId };
  } catch (err) {
    coreThrew = err instanceof Error ? err.message : String(err);
  }
  let oracleResult;
  let oracleThrew = null;
  try {
    oracleResult = oracleDecide(res, accept, lang);
  } catch (err) {
    oracleThrew = err instanceof Error ? err.message : String(err);
  }

  if (coreThrew || oracleThrew || JSON.stringify(coreResult) !== JSON.stringify(oracleResult)) {
    failures += 1;
    log('fuzz', 'DISAGREEMENT', {
      iteration: i + 1,
      accept,
      lang,
      variants: res.representations.map((r) => ({ id: r.id, media: `${r.mediaType.type}/${r.mediaType.subtype}`, params: Object.fromEntries(r.mediaType.parameters), lang: r.language })),
      core: coreResult ?? { threw: coreThrew },
      oracle: oracleResult ?? { threw: oracleThrew },
    });
    if (failagesGuard(i)) break;
  } else {
    agreements += 1;
    if ((i + 1) % 100 === 0) log('fuzz', `progress ${i + 1}/${ITERATIONS}`, { agreements });
  }
}
function failagesGuard() {
  return failures >= 10; // stop after a few concrete disagreements
}

log('summary', failures === 0 ? 'ALL ORACLE CHECKS PASSED' : 'ORACLE CHECKS FAILED', {
  handVectors: VECTORS.length,
  fuzzIterations: ITERATIONS,
  agreements,
  failures,
});
if (failures > 0) process.exit(1);
