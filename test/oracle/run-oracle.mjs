/**
 * Oracle test runner (plain Node, no test framework dependency).
 *
 *   node test/oracle/run-oracle.mjs [fuzzIterations] [seed]
 *
 * Phase 1: hand-authored vectors with exact, human-computed winner / failure.
 * Phase 2: seeded differential fuzzing comparing the independent oracle with
 * the compiled production core. Every line carries a run id, the service
 * version and progress. A parse error, thrown exception, or disagreement is a
 * hard failure with process exit code 1 - never silently reported as success.
 */
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { negotiate } from '../../dist/src/core/negotiator.js';
import { oracleDecide } from './oracle.mjs';

const RUN_ID = process.env.ORACLE_RUN_ID ?? randomUUID();
const VERSION = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8')).version;
const ITERATIONS = Number(process.argv[2] ?? 500);
const SEED = Number(process.argv[3] ?? 20260928);

const log = (phase, msg, extra = {}) =>
  console.log(JSON.stringify({ runId: RUN_ID, serviceVersion: VERSION, phase, msg, ...extra }));

function mt(type, subtype, params = {}) {
  return { type, subtype, parameters: new Map(Object.entries(params)) };
}
function rep(id, type, subtype, lang, params) {
  return { id, mediaType: mt(type, subtype, params), language: lang, charset: 'utf-8', body: id };
}
function resource(id, reps) {
  return { id, name: id, representations: reps };
}

