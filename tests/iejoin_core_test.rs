//! Core differential tests: IEJoin vs the independent nested-loop oracle.
//!
//! These answer the concrete questions from the spec for ALL FOUR inequality
//! directions plus mixed orientations, over: a hand fixture, all-equal values,
//! empty sides, high-selectivity data, dense duplicates, nulls and seeded
//! random data. Each case asserts the exact result MULTISET and records the
//! IEJoin candidate-access count, so a result is accepted only when the set of
//! `(left_row, right_row)` pairs matches exactly with multiplicities.
//!
//! The oracle (`nested_loop`) shares no join logic with the core under test.

mod common;

use std::collections::HashMap;

use common::{fixed_datasets, random, ALL_DIRECTIONS};
use iejoin_range::operator::nested_loop::nested_loop;
use iejoin_range::operator::{join_full, Comparator, JoinPlan, OutputPair, Predicate};
use iejoin_range::resource::Budget;
use iejoin_range::types::builder::{batch, int_column};
use iejoin_range::PreparedJoin;

/// Multiset of pairs: maps (left_row, right_row) to its multiplicity.
fn multiset(pairs: &[OutputPair]) -> HashMap<(u64, u64), usize> {
    let mut m = HashMap::new();
    for p in pairs {
        *m.entry((p.left_row, p.right_row)).or_default() += 1;
    }
    m
}

fn assert_same_multiset(actual: &[OutputPair], expected: &[OutputPair], context: &str) {
    let a = multiset(actual);
    let e = multiset(expected);
    assert_eq!(
        a, e,
        "multiset mismatch for {context}\nactual={:?}\nexpected={:?}",
        actual, expected
    );
}

/// Run core and oracle for a direction/dataset and compare multisets; return
/// the candidate-access statistic so callers can also assert on work.
fn check_case(plan: &JoinPlan, ds: &common::Dataset) -> u64 {
    let expected = nested_loop(plan, &ds.left, &ds.right)
        .unwrap_or_else(|e| panic!("oracle failed on {}: {e:?}", ds.name));
    let page = join_full(plan, &ds.left, &ds.right, &Budget::unlimited())
        .unwrap_or_else(|e| panic!("iejoin failed on {}: {e:?}", ds.name));
    assert_same_multiset(&page.pairs, &expected, &format!("{} / {:?}", ds.name, plan));
    page.stats.candidate_accesses
}

#[test]
fn all_four_directions_match_oracle_on_every_fixed_dataset() {
    for dir in ALL_DIRECTIONS {
        let plan = dir.plan();
        for ds in fixed_datasets() {
            let accesses = check_case(&plan, &ds);
            // Work sanity: candidate probes never exceed all pairs touched.
            let (nl, nr) = ds.sizes();
            assert!(
                accesses <= nl as u64 * nr as u64 + (nl + nr) as u64,
                "candidate accesses {accesses} implausible for {}x{} on {}",
                nl,
                nr,
                ds.name
            );
        }
    }
}

#[test]
fn seeded_random_datasets_match_oracle() {
    // Several seeds, sizes and null ratios; all six directions.
    for seed in [1u64, 2, 7, 42, 99] {
        for (nl, nr) in [(8, 6), (15, 15), (1, 20), (20, 1)] {
            let ds = random(seed, nl, nr, 12, 25);
            for dir in ALL_DIRECTIONS {
                check_case(&dir.plan(), &ds);
            }
        }
    }
}

