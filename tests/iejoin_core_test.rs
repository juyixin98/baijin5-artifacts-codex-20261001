#[test]
fn strict_band_has_exact_hand_verified_pairs() {
    let ds = common::hand_small();
    // Predicate: a1 > b1 AND a2 < b2.
    // left rows:
    //  0: (5,7)  1: (2,7)  2: (5,1)  3: (9,3)  4: NULL -> never matches
    // right rows:
    //  0: (5,7)  1: (1,9)  2: (2,0)  3: (9,4)  4: (6,NULL)
    let plan = JoinPlan::new(
        Predicate {
            left_col: 0,
            right_col: 0,
            op: Comparator::Gt,
        },
        Predicate {
            left_col: 1,
            right_col: 1,
            op: Comparator::Lt,
        },
    );
    let page = join_full(&plan, &ds.left, &ds.right, &Budget::unlimited()).unwrap();
    // Enumerated by hand:
    //  L0(5,7): r0(5,7) no(=), r1(1,9) 5>1 & 7<9 YES, r2(2,0) 7<0 no,
    //          r3(9,4) 5>9 no, r4 null no -> {1}
    //  L1(2,7): r1(1,9) 2>1 & 7<9 YES -> {1}; others no
    //  L2(5,1): r1(1,9) 5>1 & 1<9 YES; r2(2,0) 1<0 no -> {1}
    //  L3(9,3): r1(1,9) 9>1 & 3<9 YES; r2(2,0) 3<0 no;
    //          r0(5,7) 9>5 & 3<7 YES -> {0,1}
    //  L4 null -> {}
    let mut want = vec![
        OutputPair {
            left_row: 0,
            right_row: 1,
        },
        OutputPair {
            left_row: 1,
            right_row: 1,
        },
        OutputPair {
            left_row: 2,
            right_row: 1,
        },
        OutputPair {
            left_row: 3,
            right_row: 0,
        },
        OutputPair {
            left_row: 3,
            right_row: 1,
        },
    ];
    want.sort_by_key(|p| (p.left_row, p.right_row));
    let mut got = page.pairs.clone();
    got.sort_by_key(|p| (p.left_row, p.right_row));
    assert_eq!(got, want, "exact hand-verified answer");
    // And it must agree with the independent oracle too.
    assert_same_multiset(
        &page.pairs,
        &nested_loop(&plan, &ds.left, &ds.right).unwrap(),
        "hand",
    );
}

#[test]
fn all_equal_strict_is_empty_nonstrict_is_full_product() {
    let ds = common::all_equal(3, 4);
    let strict = JoinPlan::new(
        Predicate {
            left_col: 0,
            right_col: 0,
            op: Comparator::Lt,
        },
        Predicate {
            left_col: 1,
            right_col: 1,
            op: Comparator::Lt,
        },
    );
    let nonstrict = JoinPlan::new(
        Predicate {
            left_col: 0,
            right_col: 0,
            op: Comparator::Le,
        },
        Predicate {
            left_col: 1,
            right_col: 1,
            op: Comparator::Le,
        },
    );
    let s = join_full(&strict, &ds.left, &ds.right, &Budget::unlimited()).unwrap();
    let n = join_full(&nonstrict, &ds.left, &ds.right, &Budget::unlimited()).unwrap();
    assert!(
        s.pairs.is_empty(),
        "strict comparison over identical keys yields nothing"
    );
    assert_eq!(
        n.pairs.len(),
        3 * 4,
        "non-strict yields the full 3x4 product with multiplicity"
    );
    assert_same_multiset(
        &n.pairs,
        &nested_loop(&nonstrict, &ds.left, &ds.right).unwrap(),
        "all-equal",
    );
}

#[test]
fn empty_side_yields_no_pairs_and_no_accesses() {
    for ds in [common::empty_left(), common::empty_right()] {
        for dir in ALL_DIRECTIONS {
            let page = join_full(&dir.plan(), &ds.left, &ds.right, &Budget::unlimited()).unwrap();
            assert!(
                page.pairs.is_empty(),
                "{} on {} must be empty",
                dir.label(),
                ds.name
            );
            assert_eq!(
                page.stats.candidate_accesses, 0,
                "no probing when a side is empty"
            );
        }
    }
}

#[test]
fn duplicates_preserve_identity_and_multiplicity() {
    let ds = common::dense_duplicates(4, 3);
    for dir in ALL_DIRECTIONS {
        let page = join_full(&dir.plan(), &ds.left, &ds.right, &Budget::unlimited()).unwrap();
        let reference = nested_loop(&dir.plan(), &ds.left, &ds.right).unwrap();
        assert_eq!(
            page.pairs.len(),
            reference.len(),
            "pair count on {}",
            ds.name
        );
        assert_same_multiset(&page.pairs, &reference, &format!("{} duplicates", ds.name));
    }
}

#[test]
fn nulls_never_match_in_any_direction() {
    let ds = common::with_nulls(12);
    for dir in ALL_DIRECTIONS {
        let plan = dir.plan();
        let page = join_full(&dir.plan(), &ds.left, &ds.right, &Budget::unlimited()).unwrap();
        let reference = nested_loop(&plan, &ds.left, &ds.right).unwrap();
        assert_same_multiset(&page.pairs, &reference, "null handling");
        // Explicit: every emitted pair has non-null keys on both columns.
        let l1 = ds.left.column(0).unwrap().to_scalars();
        let l2 = ds.left.column(1).unwrap().to_scalars();
        let r1 = ds.right.column(0).unwrap().to_scalars();
        let r2 = ds.right.column(1).unwrap().to_scalars();
        for p in &page.pairs {
            assert!(!l1[p.left_row as usize].is_null());
            assert!(!l2[p.left_row as usize].is_null());
            assert!(!r1[p.right_row as usize].is_null());
            assert!(!r2[p.right_row as usize].is_null());
        }
    }
}

#[test]
fn high_selectivity_exact_count_and_fewer_accesses_than_nested_loop() {
    let ds = common::high_selectivity(20);
    let plan = JoinPlan::new(
        Predicate {
            left_col: 0,
            right_col: 0,
            op: Comparator::Gt,
        },
        Predicate {
            left_col: 1,
            right_col: 1,
            op: Comparator::Gt,
        },
    );
    let page = join_full(&plan, &ds.left, &ds.right, &Budget::unlimited()).unwrap();
    let reference = nested_loop(&plan, &ds.left, &ds.right).unwrap();
    assert_same_multiset(&page.pairs, &reference, "high selectivity");
    // Only the three planted band rows can match → exactly 3 * (matching lefts).
    // Assert the exact, independently counted number rather than "some rows".
    assert!(
        reference.len() <= 20 * 3,
        "bounded by the three planted band rows"
    );
    assert!(
        page.stats.candidate_accesses < 20 * 20,
        "IEJoin should probe fewer than the 400 pair NL"
    );
}

