"""Independent oracle for digest tests.

This reference is deliberately written from scratch with plain string
scanning; it imports NOTHING from the implementation under test, so expected
answers cannot be generated by the core code validating itself.

Convention (matches the service spec):
  * 1-based residues; bond i is between residues i and i+1.
  * cut after a residue in `cut_after`, unless the next residue is in
    `not_before`.
  * fragments are substrings between cut bonds; k missed cleavages unions up
    to k+1 adjacent primary fragments.
"""

from __future__ import annotations


def oracle_primary_fragments(seq: str, cut_after: str, not_before: str):
    cuts = []
    for i in range(len(seq) - 1):
        if seq[i] in cut_after and seq[i + 1] not in not_before:
            cuts.append(i + 1)  # bond index = P1 1-based position
    bounds = [0, *cuts, len(seq)]
    pieces = []
    for left, right in zip(bounds[:-1], bounds[1:]):
        if right > left:
            pieces.append((seq[left:right], left + 1, right))
    return cuts, pieces


def oracle_all_fragments(seq: str, cut_after: str, not_before: str, max_mc: int):
    cuts, pieces = oracle_primary_fragments(seq, cut_after, not_before)
    all_frags = []
    m = len(pieces)
    for i in range(m):
        for j in range(i, min(m - 1, i + max_mc) + 1):
            start = pieces[i][1]
            end = pieces[j][2]
            all_frags.append((seq[start - 1:end], start, end, j - i))
    return cuts, all_frags


