"""Independent reference oracle for cross-checking the core under test.

NOTHING here imports :mod:`miniseed.minimizer` or :mod:`miniseed.hashing`.
The golden expectations in the tests are produced by this deliberately
simplistic, separately written implementation:

* hash: textbook FNV-1a over independently declared two-bit codes;
* minimizers: full per-window enumeration (no deque), explicit ``min`` with
  a ``(hash, leftmost_offset)`` key;
* dedup: first value of each maximal run of identical picks over adjacent
  N-eligible windows.

It exists so the test reference answer cannot be generated by the very
implementation being validated.
"""
from __future__ import annotations

_FNV_OFFSET = 0xCBF29CE484222325
_FNV_PRIME = 0x100000001B3
_MASK = (1 << 64) - 1
_MOD = 1 << 63
_CODE = {"A": 0, "C": 1, "G": 2, "T": 3}
_RC = {"A": "T", "C": "G", "G": "C", "T": "A", "N": "N"}


def golden_hash(canonical_kmer: str) -> int:
    h = _FNV_OFFSET
    for ch in canonical_kmer:
        h = ((h ^ _CODE[ch]) * _FNV_PRIME) & _MASK
    return h % _MOD


def golden_revcomp(seq: str) -> str:
    return "".join(_RC[c] for c in seq[::-1])


def golden_canonical(kmer: str) -> tuple[str, str]:
    rc = golden_revcomp(kmer)
    if kmer <= rc:
        return kmer, "+"
    return rc, "-"


def golden_window_picks(seq: str, k: int, w: int) -> list[tuple[int, int] | None]:
    """Brute-force (offset, hash) pick per window; ``None`` if all N k-mers."""
    picks: list[tuple[int, int] | None] = []
    n_windows = len(seq) - k - w + 2
    for s in range(n_windows):
        best: tuple[int, int] | None = None
        for i in range(w):
            off = s + i
            kmer = seq[off : off + k]
            if "N" in kmer:
                continue
            canon, _orient = golden_canonical(kmer)
            key = (golden_hash(canon), off)
            if best is None or key < best:
                best = key
        picks.append(best)
    return picks


def golden_minimizers(seq: str, k: int, w: int) -> list[dict]:
    """Expected deduplicated minimizer records (first value per adjacent run)."""
    picks = golden_window_picks(seq, k, w)
    out: list[dict] = []
    prev_hash: int | None = None
    prev_eligible = False
    for s, pick in enumerate(picks):
        if pick is None:
            prev_eligible = False
            continue
        hv, off = pick
        if not prev_eligible or hv != prev_hash:
            canon, orient = golden_canonical(seq[off : off + k])
            out.append(
                {
                    "offset": off,
                    "window_index": s,
                    "hash": hv,
                    "canonical": canon,
                    "orientation": orient,
                }
            )
        prev_hash = hv
        prev_eligible = True
    return out
