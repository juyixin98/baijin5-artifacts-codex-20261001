"""Independent brute-force reference implementations.

These enumerate *every* legal path by plain recursion and are used as the
oracle for the DP kernel on small inputs.  They share no code with
``app.kernel`` — the reference answers are not generated by the
implementation under test.
"""

from __future__ import annotations

import numpy as np


def _clamp(c: int, width: int) -> int:
    return min(max(c, 0), width - 1)


def forward_step_cost(lum: np.ndarray, row: int, col: int, prev_col: int) -> float:
    """Cost of the seam arriving at (row, col) from (row-1, prev_col)."""
    width = lum.shape[1]
    left = lum[row, _clamp(col - 1, width)]
    right = lum[row, _clamp(col + 1, width)]
    cu = abs(right - left)
    if prev_col == col:
        return float(cu)
    if prev_col == col - 1:  # stepped right -> CR
        return float(cu + abs(lum[row - 1, col] - right))
    if prev_col == col + 1:  # stepped left -> CL
        return float(cu + abs(lum[row - 1, col] - left))
    raise ValueError(f"illegal step {prev_col} -> {col}")


def path_cost_gradient(energy: np.ndarray, path: list[int]) -> float:
    return float(sum(energy[r, c] for r, c in enumerate(path)))


def path_cost_forward(lum: np.ndarray, path: list[int]) -> float:
    return float(
        sum(forward_step_cost(lum, r, path[r], path[r - 1]) for r in range(1, len(path)))
    )


def brute_force_gradient(
    energy: np.ndarray, mask: np.ndarray, max_displacement: int
) -> tuple[float, list[int]] | None:
    """Min-cost legal path over the energy surface; None if none exists."""
    height, width = energy.shape
    best: tuple[float, list[int]] | None = None

    def rec(row: int, col: int, cost: float, path: list[int]) -> None:
        nonlocal best
        if mask[row, col]:
            return
        cost += float(energy[row, col])
        path = path + [col]
        if row == height - 1:
            if best is None or cost < best[0] - 1e-9:
                best = (cost, path)
            return
        lo = max(0, col - max_displacement)
        hi = min(width - 1, col + max_displacement)
        for nxt in range(lo, hi + 1):
            rec(row + 1, nxt, cost, path)

    for start in range(width):
        rec(0, start, 0.0, [])
    return best


def brute_force_forward(
    lum: np.ndarray, mask: np.ndarray
) -> tuple[float, list[int]] | None:
    """Min-cost legal path under forward energy (displacement 1)."""
    height, width = lum.shape
    best: tuple[float, list[int]] | None = None

    def rec(row: int, col: int, cost: float, path: list[int]) -> None:
        nonlocal best
        if mask[row, col]:
            return
        path = path + [col]
        if row == height - 1:
            if best is None or cost < best[0] - 1e-9:
                best = (cost, path)
            return
        for nxt in (col - 1, col, col + 1):
            if 0 <= nxt < width:
                rec(row + 1, nxt, cost + forward_step_cost(lum, row + 1, nxt, col), path)

    for start in range(width):
        rec(0, start, 0.0, [])
    return best
