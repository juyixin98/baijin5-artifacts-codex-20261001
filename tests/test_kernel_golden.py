"""Golden-value tests.

Chain of trust:
  published constants (Lindbloom / IEC 61966-2-1)
      -> tests/reference/analytic.py (spec formulas, asserted here)
      -> fixtures/golden_vectors.json (generated by tools/make_fixtures.py)
      -> colorconvert kernel output (asserted against the JSON)

The kernel (LittleCMS) never generates its own reference values.
"""
from __future__ import annotations

import json

import numpy as np
import pytest

from colorconvert.contract import ColorMode, ImageData
from colorconvert.kernel import RenderingIntent
from tests.reference import analytic

from .conftest import FIXTURES

# Published reference values (Bruce Lindbloom's sRGB calculator, D50 PCS).
PUBLISHED_LAB_D50 = {
    "red": ((255, 0, 0), (54.29, 80.81, 69.89)),
    "green": ((0, 255, 0), (87.82, -79.29, 80.99)),
    "blue": ((0, 0, 255), (29.57, 68.30, -112.03)),
    "white": ((255, 255, 255), (100.0, 0.0, 0.0)),
    "black": ((0, 0, 0), (0.0, 0.0, 0.0)),
}


@pytest.mark.parametrize(
    "name", ["red", "green", "blue", "white", "black"]
)
def test_analytic_reference_matches_published_constants(name):
    rgb, expected_lab = PUBLISHED_LAB_D50[name]
    lab = analytic.srgb8_to_lab_d50(rgb)
    assert np.allclose(lab, expected_lab, atol=0.5), (
        f"analytic reference drifted for {name}: {lab} vs {expected_lab}"
    )


def test_analytic_white_point_xyz():
    xyz = analytic.linear_srgb_to_xyz(analytic.srgb8_to_linear((255, 255, 255)))
    assert np.allclose(xyz, (0.9505, 1.0, 1.0890), atol=1e-3)


@pytest.fixture(scope="module")
def golden():
    return json.loads((FIXTURES / "golden_vectors.json").read_text())[
        "vectors"
    ]


def test_kernel_matches_golden_vectors(kernel, registry, golden):
    src = registry.get("srgb", role="source")
    dst = registry.get("lab-d50", role="target")
    for vector in golden:
        rgb = vector["srgb"]
        image = ImageData(
            color=np.array([[rgb]], dtype=np.uint8), mode=ColorMode.RGB
        )
        result, report = kernel.convert(
            image, src, dst, RenderingIntent.RELATIVE_COLORIMETRIC, False
        )
        got = result.color[0, 0].astype(int)
        expected = np.array(vector["pillow_lab8"], dtype=int)
        # 8-bit Lab quantization: L 1 LSB ~ 0.39, a/b 1 LSB = 1.0
        assert np.all(np.abs(got - expected) <= 2), (
            f"{vector['name']}: kernel {got.tolist()} vs analytic "
            f"{expected.tolist()} (lab_d50={vector['lab_d50']})"
        )
        assert report.rendering_intent == "relative_colorimetric"
        assert report.black_point_compensation is False
