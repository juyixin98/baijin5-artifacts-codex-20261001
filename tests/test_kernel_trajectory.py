"""Hand-computed threshold trajectory tests for the pure kernel.

The expected numbers are literals from the independent oracle
(scripts/print_reference_values.py), not values generated by the kernel
itself.  They cover: the official onlineFDR teaching sample, an extended
sequence, the closed-interval tie rule and strict online causality.
"""

import math

import pytest

from app.contracts import (
    B0,
    W0,
    Decision,
    LORD3State,
    replay,
    step,
)


# --- Official onlineFDR teaching sample: p = (1e-7, .1, .00025, .07) --------

OFFICIAL_SAMPLE = [1e-7, 0.1, 0.00025, 0.07]
EXPECTED_OFFICIAL = [
    # idx, gamma, threshold, rejected, wealth_before, wealth_after, tau
    (1, 0.011638205782941741, 5.819102891470871e-05, True,
     0.005, 0.049941808971085286, 1),
    (2, 0.011638205782941741, 0.0005812330499778565, False,
     0.049941808971085286, 0.04936057592110743, 1),
    (3, 0.011638205782941741, 0.0005812330499778565, True,
     0.04936057592110743, 0.09377934287112957, 3),
    (4, 0.011638205782941741, 0.0010914232905232565, False,
     0.09377934287112957, 0.09268791958060632, 3),
]


def _drive(p_values):
    state = LORD3State.initial()
    decisions = []
    for i, p in enumerate(p_values, start=1):
        state, d = step(state, f"H{i}", p)
        decisions.append(d)
    return decisions


def test_official_teaching_sample_matches_hand_computed_trajectory():
    decisions = _drive(OFFICIAL_SAMPLE)
    assert [d.rejected for d in decisions] == [True, False, True, False]
    for d, (idx, g, thr, rej, wb, wa, tau) in zip(
        decisions, EXPECTED_OFFICIAL
    ):
        assert d.index == idx
        assert d.gamma_value == pytest.approx(g, abs=1e-18)
        assert d.threshold == pytest.approx(thr, abs=1e-18)
        assert d.rejected is rej
        assert d.wealth_before == pytest.approx(wb, abs=1e-18)
        assert d.wealth_after == pytest.approx(wa, abs=1e-18)
        assert d.tau == tau


def test_official_sample_rejection_pattern_is_1010():
    # The pattern onlineFDR documents; robust to the reward-timing variant.
    decisions = _drive(OFFICIAL_SAMPLE)
    assert [int(d.rejected) for d in decisions] == [1, 0, 1, 0]


def test_extended_sequence_anchors_after_fifth_and_seventh_steps():
    decisions = _drive(
        [1e-7, 0.1, 0.00025, 0.07, 0.001, 0.9, 2e-5]
    )
    # Step 5: p == 0.001 is exactly at gamma2 * W(3) -> reject (closed).
    d5 = decisions[4]
    assert d5.threshold == pytest.approx(0.0010914232905232565, abs=1e-18)
    assert d5.rejected is True
    assert d5.wealth_after == pytest.approx(0.13659649629008308, abs=1e-18)
    assert d5.tau == 5
    # Step 7 resets gamma index to 2 after the rejection at tau = 5.
    d7 = decisions[6]
    assert d7.gamma_value == pytest.approx(0.011638205782941741, abs=1e-18)
    assert d7.threshold == pytest.approx(0.001589738133052825, abs=1e-18)
    assert d7.rejected is True
    assert d7.wealth_after == pytest.approx(0.1784170200239774, abs=1e-18)
    assert d7.tau == 7


def test_threshold_tie_at_equality_is_a_rejection():
    a1 = 0.011638205782941741 * W0
    d = _drive([a1])[0]
    assert d.threshold == pytest.approx(a1, abs=1e-22)
    assert d.rejected is True


def test_just_above_threshold_is_not_rejected():
    a1 = 0.011638205782941741 * W0
    d = _drive([math.nextafter(a1, math.inf)])[0]
    assert d.rejected is False


def test_first_threshold_depends_only_on_frozen_priors():
    # Before any outcome exists, threshold must be gamma1 * w0 regardless of
    # which p-value will be submitted.
    state = LORD3State.initial()
    for p in (0.0, 0.5, 1.0):
        _, d = step(LORD3State.initial(), "X", p)
        assert d.threshold == pytest.approx(
            0.011638205782941741 * W0, abs=1e-20
        )


def test_thresholds_never_use_current_or_future_pvalues():
    # Causality: build states deterministically from prefixes, and confirm the
    # threshold at i is identical when the p-value at i is replaced.  Only the
    # rejection/wealth AFTER the comparison may differ.
    ps = [0.42, 0.0001, 0.7, 0.00005, 0.99]
    baseline = _drive(ps)
    for i, alt in enumerate([0.0, 0.3, 0.6, 1.0, 2e-6]):
        changed = list(ps)
        changed[i] = alt
        got = _drive(changed)
        # The threshold at the changed index itself is unchanged.
        assert got[i].threshold == baseline[i].threshold
        # Index alignment of gamma: future thresholds may diverge once the
        # change alters a rejection; assert at least that the past prefix is
        # bit-identical up to the changed index.
        for j in range(i):
            assert got[j].threshold == baseline[j].threshold


def test_reward_is_added_on_rejections_own_wealth_step():
    # Paper-faithful timing: after a rejection at t, W(t) = W(t-1) - a + b0.
    d1 = _drive([1e-7])[0]
    assert d1.wealth_after == pytest.approx(W0 - d1.threshold + B0, abs=1e-18)
    # W(tau) used at step 2 already contains the step-1 reward.
    d2 = _drive([1e-7, 0.5])[1]
    assert d2.w_tau_used == pytest.approx(
        W0 - d1.threshold + B0, abs=1e-18
    )


def test_replay_entrypoint_reproduces_step_sequence():
    ps = [0.2, 0.00003, 0.8, 0.0001]
    via_replay = replay([(f"H{i}", p) for i, p in enumerate(ps, 1)])
    via_steps = _drive(ps)
    for a, b in zip(via_replay, via_steps):
        assert _same_decision(a, b)


def _same_decision(a: Decision, b: Decision) -> bool:
    return (
        a.index == b.index
        and a.hypothesis_id == b.hypothesis_id
        and a.p_value == b.p_value
        and a.threshold == b.threshold
        and a.rejected == b.rejected
        and a.wealth_after == b.wealth_after
        and a.tau == b.tau
    )
