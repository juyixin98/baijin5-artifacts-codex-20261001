"""Independent verification reference implementations.

The core data plane trusts OpenSSL (via Python's `ssl` module) and the
`cryptography` package. This module re-checks the same questions with
independent implementations, so test expectations are not generated by
the code under test:

- PyCryptodome re-verifies the leaf certificate's RSA signature against
  the issuer's public key (an independent crypto implementation).
- The `openssl verify` CLI re-runs chain building and purpose checks in
  an independent process (reported as skipped if the binary is missing).
- validity_window re-checks certificate time validity directly.
"""
from __future__ import annotations

import datetime as dt
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives.serialization import (Encoding,
                                                          PublicFormat)

from Crypto.Hash import SHA256, SHA384, SHA512
from Crypto.PublicKey import RSA
from Crypto.Signature import pkcs1_15

from .certs import cert_validity_utc

_HASHES = {"sha256": SHA256, "sha384": SHA384, "sha512": SHA512}
UTC = dt.timezone.utc


@dataclass
class VerifyReport:
    ok: bool
    checker: str
    detail: str
    skipped: bool = False


def pycryptodome_verify_leaf_signature(leaf_der: bytes,
                                       issuer_der: bytes) -> VerifyReport:
    """Re-verify the leaf's signature with PyCryptodome (not OpenSSL)."""
    leaf = x509.load_der_x509_certificate(leaf_der)
    issuer = x509.load_der_x509_certificate(issuer_der)
    hash_alg = leaf.signature_hash_algorithm
    hash_name = hash_alg.name if hash_alg is not None else None
    hash_mod = _HASHES.get(hash_name or "")
    if hash_mod is None:
        return VerifyReport(False, "pycryptodome",
                            f"unsupported signature hash {hash_name!r}")
    issuer_pub_der = issuer.public_key().public_bytes(
        Encoding.DER, PublicFormat.SubjectPublicKeyInfo
    )
    rsa_key = RSA.import_key(issuer_pub_der)
    digest = hash_mod.new(leaf.tbs_certificate_bytes)
    try:
        pkcs1_15.new(rsa_key).verify(digest, leaf.signature)
        return VerifyReport(
            True, "pycryptodome",
            f"RSA/{hash_name} signature over TBS certificate is valid",
        )
    except (ValueError, TypeError) as exc:
        return VerifyReport(False, "pycryptodome",
                            f"signature verification failed: {exc}")


def openssl_verify(leaf_pem: str, roots_pem: str, *,
                   purpose: str = "sslclient",
                   untrusted_pem: str = "") -> VerifyReport:
    """Re-run chain building + purpose check with the openssl CLI."""
    if shutil.which("openssl") is None:
        return VerifyReport(False, "openssl-cli",
                            "openssl binary not found", skipped=True)
    with tempfile.TemporaryDirectory() as td:
        leaf_path = Path(td) / "leaf.pem"
        roots_path = Path(td) / "roots.pem"
        leaf_path.write_text(leaf_pem)
        roots_path.write_text(roots_pem)
        cmd = ["openssl", "verify", "-CAfile", str(roots_path),
               "-purpose", purpose]
        if untrusted_pem:
            chain_path = Path(td) / "chain.pem"
            chain_path.write_text(untrusted_pem)
            cmd += ["-untrusted", str(chain_path)]
        cmd.append(str(leaf_path))
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=30)
        detail = (proc.stdout + proc.stderr).strip()
        return VerifyReport(proc.returncode == 0, "openssl-cli", detail)


def validity_window(cert_der: bytes,
                    at: dt.datetime | None = None) -> VerifyReport:
    """Independently re-check the certificate validity window."""
    cert = x509.load_der_x509_certificate(cert_der)
    at = at or dt.datetime.now(UTC)
    not_before, not_after = cert_validity_utc(cert)
    if at < not_before:
        return VerifyReport(False, "validity-window",
                            f"not valid before {not_before}")
    if at > not_after:
        return VerifyReport(False, "validity-window",
                            f"expired at {not_after}")
    return VerifyReport(True, "validity-window",
                        f"valid until {not_after}")
